message = 'Devyaniiiiiiiiiii'

print(message.lower())
print(message.upper())
print(message.replace('D', 'd'))
print(message.split('y'))
print('find:', message.find('vya'))  # index of the first occurrence
print(message.startswith('Dev'))
print(message.endswith('ani'))
print(message.count('i'))
print(message.isalnum())  # all characters alphanumeric
print(message.isalpha())  # all characters alphabetic
print(message.isdigit())  # all characters digits
