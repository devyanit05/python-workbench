# ------------------------------------------------------------------------
# If Else Elif Statements
# ------------------------------------------------------------------------

if True:
    print('true')

if False:
    print('false')
else:
    print('true')

language = 'Python'

if language == 'Python':
    print('Language is Python')
elif language == 'Java':
    print('Language is Java')
else:
    print('Language is something else')

num = -7

if num > 0:
    print('Positive')
elif num < 0:
    print('Negative')
else:
    print('Zero')
